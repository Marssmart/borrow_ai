#!/usr/bin/env python3
"""Build the GitHub Pages site in docs/ from the repository sources.

Sources:
  site/content/*.md      hand-written app documentation (one page per file)
  site/assets/style.css  site stylesheet
  features/<folder>/     one collection per folder: *.md rendered to pages, *.html copied as-is
  design/                design guides (*.html copied as-is)

Requirements: Python 3.9+ (standard library only) and pandoc on PATH for Markdown rendering.
Run from anywhere: python3 scripts/build_docs.py. Commit the regenerated docs/ folder.
"""

import html
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT_DIR = ROOT / "site" / "content"
ASSETS_DIR = ROOT / "site" / "assets"
FEATURES_DIR = ROOT / "features"
DESIGN_DIR = ROOT / "design"
OUT_DIR = ROOT / "docs"

NAV = [
    ("index.html", "Home"),
    ("how-it-works.html", "How it works"),
    ("architecture.html", "Architecture"),
    ("models-and-privacy.html", "Models and privacy"),
    ("platforms.html", "Platforms"),
    ("features/index.html", "Features"),
    ("design/index.html", "Design guides"),
    ("developing.html", "Developing"),
]

H1_PATTERN = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
TITLE_PATTERN = re.compile(r"<title>(.*?)</title>", re.IGNORECASE | re.DOTALL)
HREF_PATTERN = re.compile(r'href="([^"]+)"')
TITLE_PREFIX = "BorrowAI — "


def prettify(name: str) -> str:
    return name.replace("-", " ").replace("_", " ").strip().capitalize()


def render_markdown(path: Path) -> str:
    try:
        result = subprocess.run(
            ["pandoc", "-f", "gfm", "-t", "html5", "--wrap=none", str(path)],
            check=True,
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        sys.exit("pandoc is required to render Markdown. Install it (for example: brew install pandoc).")
    except subprocess.CalledProcessError as error:
        sys.exit(f"pandoc failed on {path}: {error.stderr.strip()}")
    return result.stdout


def markdown_title(path: Path) -> str:
    match = H1_PATTERN.search(path.read_text(encoding="utf-8"))
    return match.group(1) if match else prettify(path.stem)


def html_title(path: Path) -> str:
    match = TITLE_PATTERN.search(path.read_text(encoding="utf-8"))
    title = match.group(1).strip() if match else prettify(path.stem)
    return title.removeprefix(TITLE_PREFIX)


def layout(rel_path: str, title: str, body: str) -> str:
    depth = rel_path.count("/")
    prefix = "../" * depth
    # Pages inside a section (features/..., design/...) highlight that section's nav entry.
    active = f"{rel_path.split('/')[0]}/index.html" if depth else rel_path
    links = []
    for href, label in NAV:
        current = ' aria-current="page"' if href == active else ""
        links.append(f'      <a href="{prefix}{href}"{current}>{html.escape(label)}</a>')
    nav_links = "\n".join(links)
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{html.escape(title)} — BorrowAI docs</title>
  <link rel="stylesheet" href="{prefix}assets/style.css">
</head>
<body>
  <header class="site-header">
    <a class="brand" href="{prefix}index.html">BorrowAI</a>
    <nav>
{nav_links}
    </nav>
  </header>
  <main>
{body}
  </main>
  <footer>Generated by <code>scripts/build_docs.py</code> from the repository. Edit the sources, not <code>docs/</code>.</footer>
</body>
</html>
"""


def write_page(rel_path: str, title: str, body: str) -> None:
    target = OUT_DIR / rel_path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(layout(rel_path, title, body), encoding="utf-8")


def build_collection(source: Path, rel_dir: str, title: str, intro: str = "") -> list[tuple[str, str]]:
    """Render a folder of documents into rel_dir and write its index page."""
    documents: list[tuple[str, str]] = []
    for path in sorted(source.iterdir()):
        if path.name.startswith(".") or path.is_dir():
            continue
        if path.suffix == ".md":
            page_name = path.stem.lower().replace("_", "-") + ".html"
            label = markdown_title(path)
            write_page(f"{rel_dir}/{page_name}", label, f"<article>\n{render_markdown(path)}</article>")
            documents.append((page_name, label))
        elif path.suffix == ".html":
            (OUT_DIR / rel_dir).mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, OUT_DIR / rel_dir / path.name)
            documents.append((path.name, html_title(path)))

    if not documents:
        sys.exit(f"{source} has no .md or .html documents; every features/ folder needs a page.")

    items = "\n".join(
        f'      <li><a href="{html.escape(href)}">{html.escape(label)}</a></li>' for href, label in documents
    )
    body = f'<article>\n  <h1>{html.escape(title)}</h1>\n  {intro}\n  <ul class="doc-list">\n{items}\n  </ul>\n</article>'
    write_page(f"{rel_dir}/index.html", title, body)
    return documents


def build_features() -> None:
    folders = sorted(path for path in FEATURES_DIR.iterdir() if path.is_dir() and not path.name.startswith("."))
    if not folders:
        sys.exit("features/ has no feature folders.")
    entries = []
    for folder in folders:
        documents = build_collection(folder, f"features/{folder.name}", prettify(folder.name))
        entries.append((folder.name, len(documents)))
    items = "\n".join(
        f'      <li><a href="{html.escape(slug)}/index.html">{html.escape(prettify(slug))}</a> '
        f"({count} document{'s' if count != 1 else ''})</li>"
        for slug, count in entries
    )
    body = (
        "<article>\n  <h1>Features</h1>\n"
        "  <p>Each folder under <code>features/</code> in the repository is listed here, with its design documents "
        "and visual guides.</p>\n"
        f'  <ul class="doc-list">\n{items}\n  </ul>\n</article>'
    )
    write_page("features/index.html", "Features", body)


def build_design() -> None:
    build_collection(DESIGN_DIR, "design", "Design guides", "<p>Design guides for the app's screens and components.</p>")


def build_content() -> None:
    for path in sorted(CONTENT_DIR.glob("*.md")):
        write_page(path.stem + ".html", markdown_title(path), f"<article>\n{render_markdown(path)}</article>")


def check_links() -> list[str]:
    problems = []
    for page in OUT_DIR.rglob("*.html"):
        for href in HREF_PATTERN.findall(page.read_text(encoding="utf-8")):
            if href.startswith(("http://", "https://", "mailto:", "#")):
                continue
            target = (page.parent / href.split("#")[0]).resolve()
            if not target.exists():
                problems.append(f"{page.relative_to(ROOT)} -> {href}")
    return problems


def main() -> None:
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)
    (OUT_DIR / ".nojekyll").touch()
    shutil.copytree(ASSETS_DIR, OUT_DIR / "assets")

    build_content()
    build_features()
    build_design()

    problems = check_links()
    if problems:
        print("Broken local links:", *problems, sep="\n  ")
        sys.exit(1)
    print(f"Built {len(list(OUT_DIR.rglob('*.html')))} pages into {OUT_DIR.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
